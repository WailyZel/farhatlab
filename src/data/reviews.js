const MS_DAY = 86400000;
const NOW = new Date('2026-10-22T12:00:00Z').getTime();

function pick(rnd, arr) {
  return arr[Math.floor(rnd() * arr.length)];
}

function genReviews(product) {
  const rnd = mulberry32(product.id * 104729 + 7);
  const cat = categoryBySlug[product.categorySlug];
  const a = aspects[product.categorySlug];
  const count = 4 + Math.floor(rnd() * 3); // 4–6 отзывов
  const usedNames = new Set();
  const list = [];
  for (let i = 0; i < count; i++) {
    let name = pick(rnd, names);
    while (usedNames.has(name)) name = pick(rnd, names);
    usedNames.add(name);
    // оценка тянется к рейтингу товара
    const r = rnd();
    let stars;
    if (r < 0.06) stars = 3;
    else if (r < 0.22 + (5 - product.rating) * 0.5) stars = 4;
    else stars = 5;
    const ctx = { purpose: cat.purpose, brand: product.brand, good: pick(rnd, a.good), bad: pick(rnd, a.bad) };
    const text = stars === 5 || stars === 4 ? (stars === 4 && rnd() < 0.5 ? pick(rnd, midTemplates)(ctx) : pick(rnd, posTemplates)(ctx)) : pick(rnd, midTemplates)(ctx);
    const date = new Date(NOW - Math.floor(rnd() * 170) * MS_DAY).toISOString().slice(0, 10);
    list.push({ id: `demo-${product.id}-${i}`, productId: product.id, author: name, rating: stars, text, date, demo: true });
  }
  return list.sort((x, y) => (x.date < y.date ? 1 : -1));
}

export const demoReviewsByProduct = new Map(products.map((p) => [p.id, genReviews(p)]));

// Подбираем распределение оценок 5/4/3/2/1 под средний рейтинг товара и общее число отзывов
export function ratingDistribution(rating, total) {
  if (total <= 0) return { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 };
  const mean = (lam) => {
    let s = 0, w = 0;
    for (let k = 1; k <= 5; k++) {
      const e = Math.exp(lam * k);
      s += k * e;
      w += e;
    }
    return s / w;
  };
  let lo = 0, hi = 4;
  for (let i = 0; i < 40; i++) {
    const mid = (lo + hi) / 2;
    if (mean(mid) < rating) lo = mid;
    else hi = mid;
  }
  const lam = (lo + hi) / 2;
  const weights = [1, 2, 3, 4, 5].map((k) => Math.exp(lam * k));
  const sum = weights.reduce((x, y) => x + y, 0);
  const raw = weights.map((w) => (w / sum) * total);
  const out = raw.map(Math.floor);
  let rest = total - out.reduce((x, y) => x + y, 0);
  const order = raw.map((v, i) => [v - Math.floor(v), i]).sort((x, y) => y[0] - x[0]);
  for (let i = 0; rest > 0; i = (i + 1) % 5, rest--) out[order[i][1]]++;
  return { 1: out[0], 2: out[1], 3: out[2], 4: out[3], 5: out[4] };
}

// Итоговая статистика: базовые данные товара + пользовательские отзывы
export function ratingStats(product, userReviews = []) {
  const base = ratingDistribution(product.rating, product.reviewCount);
  const dist = { ...base };
  let sum = product.rating * product.reviewCount;
  let total = product.reviewCount;
  for (const r of userReviews) {
    dist[r.rating]++;
    sum += r.rating;
    total++;
  }
  return { distribution: dist, total, average: total ? Math.round((sum / total) * 10) / 10 : 0 };
}

// Отзывы для главной страницы — по одному яркому отзыву у популярных товаров
export function featuredReviews(limit = 6) {
  const result = [];
  for (const p of products) {
    if (!p.isPopular) continue;
    const r = demoReviewsByProduct.get(p.id).find((x) => x.rating === 5);
    if (r) result.push({ ...r, productName: p.name });
    if (result.length >= limit) break;
  }
  return result;
}
